import type { Metadata } from "next";
import Link from "next/link";
import { db } from "@/lib/db";
import { requireArea } from "@/lib/auth/guards";
import { ensureProfile } from "@/lib/services/profile";
import { getProvider } from "@/lib/ai/provider";
import { ActionForm, SubmitButton } from "@/components/forms";
import { Badge, EmptyState, Field, PageHeader, Panel } from "@/components/ui";
import { decideAiAction, requestAiAction } from "@/app/actions/ai";
import { AI_KINDS } from "@/lib/services/ai";
import type { AiFlag } from "@/lib/ai/guard";
import type { ResumeContent } from "@/lib/resume/types";
import { timeAgo } from "@/lib/utils";

export const metadata: Metadata = { title: "AI assistant" };
export const dynamic = "force-dynamic";

export default async function AssistantPage({ searchParams }: { searchParams: Promise<{ resume?: string }> }) {
  const sp = await searchParams;
  const user = await requireArea("app");
  const profile = await ensureProfile(user);
  const enabled = !!getProvider();
  const [resumes, suggestions, jobs] = await Promise.all([
    db.resume.findMany({ where: { profileId: profile.id }, orderBy: { updatedAt: "desc" }, include: { versions: { orderBy: { version: "desc" }, take: 1 } } }),
    db.aiSuggestion.findMany({ where: { userId: user.id }, orderBy: { createdAt: "desc" }, take: 15 }),
    db.jobMatch.findMany({ where: { profileId: profile.id, job: { status: "ACTIVE" } }, orderBy: { score: "desc" }, take: 20, include: { job: { select: { id: true, title: true, companyName: true } } } }),
  ]);
  const resume = resumes.find((r) => r.id === sp.resume) ?? resumes[0];
  const content = resume?.versions[0]?.content as unknown as ResumeContent | undefined;
  const bullets = (content?.experiences ?? []).flatMap((e, i) => (e.description ?? "").split("\n").map((l) => l.trim()).filter(Boolean).map((b) => ({ i, role: e.title, text: b.replace(/^[•\-*]\s*/, "") }))).slice(0, 20);
  const pending = suggestions.filter((s) => s.status === "PENDING");
  const decided = suggestions.filter((s) => s.status !== "PENDING");

  return (
    <>
      <PageHeader title="AI assistant" description="Optional help with wording. It only works from facts you provide, never adds skills or experience, and nothing is saved until you approve it. Your score never depends on AI." actions={resume && <Link href={`/resume/${resume.id}/edit`} className="btn btn-secondary btn-sm">Back to editor</Link>} />
      {!enabled && <p role="note" className="mb-6 rounded-md border border-line bg-surface px-4 py-3 text-[13.5px] text-ink-2">AI assistance is switched off on this server (no API key configured). Scoring, parsing, matching and the resume builder all work without it.</p>}

      {pending.length > 0 && (
        <section className="mb-8" aria-labelledby="pending">
          <h2 id="pending" className="eyebrow mb-2">Waiting for your decision · {pending.length}</h2>
          <div className="space-y-4">
            {pending.map((s) => {
              const flags = (s.flags as unknown as AiFlag[]) ?? [];
              const blocked = flags.some((f) => f.severity === "block");
              const meta = AI_KINDS[s.kind as keyof typeof AI_KINDS];
              return (
                <article key={s.id} className="panel p-4">
                  <div className="mb-2 flex items-center justify-between gap-2"><h3 className="text-[14px]">{meta?.label ?? s.kind}</h3><span className="text-[12px] text-muted">{timeAgo(s.createdAt)} · {s.model === "deterministic" ? "built from your data (no AI)" : "generated by AI"}</span></div>
                  {s.original && <div className="mb-3"><p className="eyebrow mb-1">Your original</p><p className="prose-plain rounded-md bg-sunken p-2.5 text-[13.5px]">{s.original}</p></div>}
                  {flags.length > 0 && (
                    <ul className="mb-3 space-y-1">
                      {flags.map((f, i) => <li key={i} className={`text-[13px] ${f.severity === "block" ? "text-bad" : "text-warn"}`}>{f.severity === "block" ? "✕ Blocked: " : "△ "}{f.message}</li>)}
                    </ul>
                  )}
                  <ActionForm action={decideAiAction.bind(null, s.id, "approve")} className="space-y-2">
                    <label className="eyebrow block" htmlFor={`o-${s.id}`}>{meta?.applies || meta?.validate ? "Draft (you can edit before approving)" : "Result"}</label>
                    <textarea id={`o-${s.id}`} name="edited" defaultValue={s.output} rows={meta?.applies ? 4 : 10} className="field" readOnly={!(meta?.applies || meta?.validate)} />
                    <div className="flex flex-wrap items-center gap-2">
                      <SubmitButton className="btn btn-accent btn-sm" pendingText="Applying…">{meta?.applies ? (s.targetType === "advice" ? "Keep" : "Approve & save") : meta?.validate ? "Keep this draft" : "Got it"}</SubmitButton>
                      {blocked && <span className="text-[12.5px] text-bad">Edit out the flagged facts to approve.</span>}
                      {meta?.applies && s.targetType === "advice" && <span className="text-[12.5px] text-muted">No target selected — approving only keeps this text.</span>}
                    </div>
                  </ActionForm>
                  <ActionForm action={decideAiAction.bind(null, s.id, "reject")} className="mt-2"><SubmitButton className="btn btn-ghost btn-sm" pendingText="…">Discard</SubmitButton></ActionForm>
                </article>
              );
            })}
          </div>
        </section>
      )}

      <div className="grid gap-6 lg:grid-cols-2">
        <Panel title="Rewrite my summary" description="Applies to your profile summary or the selected resume after you approve.">
          <ActionForm action={requestAiAction} className="space-y-3">
            <input type="hidden" name="kind" value="rewrite-summary" />
            <textarea name="text" rows={5} required defaultValue={content?.summary ?? profile.summary ?? ""} className="field" aria-label="Summary" />
            <Field label="Save approved text to" htmlFor="tt-sum">
              <select id="tt-sum" name="targetType" className="field">
                <option value="profile.summary">My profile summary</option>
                {resume && <option value="resume.summary">Resume: {resume.title}</option>}
              </select>
            </Field>
            {resume && <input type="hidden" name="resumeId" value={resume.id} />}
            <SubmitButton className="btn btn-secondary" pendingText="Thinking…" disabled={!enabled}>Suggest rewrite</SubmitButton>
          </ActionForm>
        </Panel>

        <Panel title="Turn facts into an achievement" description="Describe what you did and any real numbers. Nothing else will be added.">
          {!resume || !content?.experiences.length ? <p className="text-[13.5px] text-muted">Add a resume with at least one role first.</p> : (
            <ActionForm action={requestAiAction} className="space-y-3">
              <input type="hidden" name="kind" value="achievement-from-facts" />
              <input type="hidden" name="targetType" value="resume.experience-bullet-add" />
              <input type="hidden" name="resumeId" value={resume.id} />
              <Field label="Role" htmlFor="exp-i"><select id="exp-i" name="experienceIndex" className="field">{content.experiences.map((e, i) => <option key={i} value={i}>{e.title} — {e.company}</option>)}</select></Field>
              <Field label="Facts" htmlFor="facts" hint="e.g. Coordinated 6 disciplines on 3 hospitals using Navisworks; 4,200 clashes resolved."><textarea id="facts" name="text" rows={4} required className="field" /></Field>
              <SubmitButton className="btn btn-secondary" pendingText="Thinking…" disabled={!enabled}>Suggest bullet</SubmitButton>
            </ActionForm>
          )}
        </Panel>

        <Panel title="Job-specific help" description="Explanations and recommendations only — they never change your resume.">
          {jobs.length === 0 ? <p className="text-[13.5px] text-muted">No matched jobs yet.</p> : (
            <ActionForm action={requestAiAction} className="space-y-3">
              <Field label="Job" htmlFor="jobId"><select id="jobId" name="jobId" className="field">{jobs.map((m) => <option key={m.jobId} value={m.jobId}>{m.job.title} — {m.job.companyName} ({m.score}%)</option>)}</select></Field>
              <Field label="What do you need?" htmlFor="jk"><select id="jk" name="kind" className="field"><option value="explain-missing">Explain my missing skills</option><option value="job-recommendations">Recommendations for this job</option><option value="interview-questions">Practice interview questions</option>{enabled && <option value="cover-letter">Cover letter draft (AI)</option>}</select></Field>
              <SubmitButton className="btn btn-secondary" pendingText="Thinking…">Ask</SubmitButton>
            </ActionForm>
          )}
        </Panel>

        <Panel title="Career recommendations" description="Based on real demand in the jobs we track, not guesses.">
          <ActionForm action={requestAiAction} className="space-y-3">
            <input type="hidden" name="kind" value="career-recommendations" />
            <SubmitButton className="btn btn-secondary" pendingText="Thinking…">Get recommendations</SubmitButton>
          </ActionForm>
        </Panel>

        <Panel title="Describe a portfolio project" description="List your role, scope, tools and outcomes. The draft uses only what you list.">
          <ActionForm action={requestAiAction} className="space-y-3">
            <input type="hidden" name="kind" value="portfolio-description" />
            <textarea name="text" rows={4} required className="field" aria-label="Project facts" placeholder="e.g. BIM Coordinator on a 12-storey hospital. Federated Revit and Navisworks models, weekly clash reviews, handed over at LOD 400." />
            <SubmitButton className="btn btn-secondary" pendingText="Thinking…" disabled={!enabled}>Draft description</SubmitButton>
          </ActionForm>
        </Panel>

        <Panel title="Improve a bullet" description={resume ? `From “${resume.title}”` : undefined}>
          {bullets.length === 0 ? <p className="text-[13.5px] text-muted">No bullets found in the selected resume.</p> : (
            <ul className="space-y-3">
              {bullets.map((b, n) => (
                <li key={n} className="text-[13.5px]">
                  <p className="text-ink-2">{b.text}</p>
                  <ActionForm action={requestAiAction} className="mt-1">
                    <input type="hidden" name="kind" value="improve-bullet" />
                    <input type="hidden" name="targetType" value="resume.bullet" />
                    <input type="hidden" name="resumeId" value={resume!.id} />
                    <input type="hidden" name="experienceIndex" value={b.i} />
                    <input type="hidden" name="text" value={b.text} />
                    <SubmitButton className="btn btn-ghost btn-sm" pendingText="Thinking…" disabled={!enabled}>Improve</SubmitButton>
                  </ActionForm>
                </li>
              ))}
            </ul>
          )}
        </Panel>
      </div>

      <section className="mt-8">
        <h2 className="eyebrow mb-2">History</h2>
        {decided.length === 0 ? <EmptyState title="No past suggestions" /> : (
          <ul className="panel divide-y divide-line text-[13px]">
            {decided.map((s) => <li key={s.id} className="flex items-center justify-between gap-3 px-4 py-2.5"><span>{AI_KINDS[s.kind as keyof typeof AI_KINDS]?.label ?? s.kind}</span><span className="flex items-center gap-2"><Badge tone={s.status === "APPROVED" ? "ok" : "neutral"}>{s.status.toLowerCase()}</Badge><span className="text-muted">{timeAgo(s.decidedAt ?? s.createdAt)}</span></span></li>)}
          </ul>
        )}
      </section>
    </>
  );
}
